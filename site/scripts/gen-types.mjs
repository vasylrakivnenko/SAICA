// Generate TypeScript node interfaces from the canonical JSON Schemas in
// ../schema/*.json and write them to ../src/lib/types.generated.ts.
//
// The JSON Schemas themselves are generated from pipeline.models (Pydantic).
// So the canonical chain is:
//
//     pipeline/models.py  (Pydantic, source of truth)
//          │
//          ▼
//     validator/generate_schemas.py
//          │
//          ▼
//     schema/*.json  (generated, committed)
//          │
//          ▼
//     site/scripts/gen-types.mjs   <-- this file
//          │
//          ▼
//     site/src/lib/types.generated.ts
//
// This script runs in the site's prebuild step (see package.json).

import { compileFromFile } from 'json-schema-to-typescript';
import { writeFile, mkdir, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SITE_ROOT = resolve(__dirname, '..');
const REPO_ROOT = resolve(SITE_ROOT, '..');
const SCHEMA_DIR = join(REPO_ROOT, 'schema');
const OUT_FILE = join(SITE_ROOT, 'src', 'lib', 'types.generated.ts');

// (file, exported interface name)
const SCHEMAS = [
  ['tool.schema.json', 'Tool'],
  ['failure_mode.schema.json', 'FailureMode'],
  ['paper.schema.json', 'Paper'],
  ['taxonomy.schema.json', 'Taxonomy'],
  ['crosswalk.schema.json', 'Crosswalk'],
];

// Hand-written shared enums. json-schema-to-typescript inlines enums per
// schema, producing duplicate union types. We emit these once up top and
// post-process each generated schema to reference them, keeping the
// generated file readable and stable.
const SHARED_ENUMS = `
export type ControlParadigm = 'prevention' | 'detection' | 'correction' | 'recovery';
export type TemporalPhase = 'pre_generation' | 'in_generation' | 'post_generation';
export type AutonomyLevel = 'fully_autonomous' | 'graduated_hitl' | 'full_hitl';
export type LocusOfControl = 'model' | 'prompt' | 'context' | 'environment' | 'human';
export type MaturityStatus = 'experimental' | 'stable' | 'at_risk' | 'deprecated' | 'abandoned';
export type FailureModeId =
  | 'fabrication'
  | 'obsolescence'
  | 'dependency_blindness'
  | 'logic_error'
  | 'security_vulnerability'
  | 'scope_creep'
  | 'context_pollution'
  | 'supply_chain_attack';
export type CrosswalkConfidence = 'exact' | 'partial' | 'broader' | 'narrower' | 'related';
export type SaicaAxis =
  | 'failure_mode'
  | 'control_paradigm'
  | 'temporal_phase'
  | 'autonomy_level'
  | 'locus_of_control';

export interface CrosswalkEntry {
  taxonomy: string;
  external_id: string;
  confidence: CrosswalkConfidence;
  note?: string;
}

export interface TaxonomyCategory {
  external_id: string;
  label: string;
  description?: string;
  parent_id?: string;
}

export interface CrosswalkMapping {
  saica_value: string;
  external_id: string;
  confidence: CrosswalkConfidence;
  note?: string;
}
`;

const FOOTER = `
export interface Graph {
  tools: Record<string, Tool>;
  failureModes: Record<string, FailureMode>;
  taxonomies: Record<string, Taxonomy>;
  papers: Record<string, Paper>;
  crosswalks: Record<string, Crosswalk>;
  // Derived indexes:
  toolsByFailureMode: Record<string, string[]>;
  failureModesByTaxonomyCategory: Record<string, Record<string, string[]>>;
  kgVersion: string;
  kgLastUpdated: string; // ISO
}
`;

async function main() {
  let out = '// AUTO-GENERATED by site/scripts/gen-types.mjs from ../schema/*.json.\n';
  out += '// DO NOT EDIT by hand — regenerate via `npm run gen-types` or `npm run build`.\n';
  out += '// Source of truth: pipeline/models.py (Pydantic).\n\n';
  out += SHARED_ENUMS.trim() + '\n\n';

  const bannerSize = 2500;

  for (const [schemaFile, _name] of SCHEMAS) {
    const fullPath = join(SCHEMA_DIR, schemaFile);
    const compiled = await compileFromFile(fullPath, {
      bannerComment: '',
      additionalProperties: false,
      // Lets us compile many schemas into one file without $ref resolution.
      cwd: SCHEMA_DIR,
      declareExternallyReferenced: true,
      unknownAny: false,
      style: { semi: true, singleQuote: true },
    });
    out += postprocess(compiled).trim() + '\n\n';
  }

  out += FOOTER.trim() + '\n';

  await mkdir(dirname(OUT_FILE), { recursive: true });
  await writeFile(OUT_FILE, out, 'utf8');
  console.log(`wrote ${OUT_FILE} (${out.length} bytes)`);
}

// Replace inline enum unions with references to the shared enum types so
// the generated file stays readable and stable. Also drops the
// "[k: string]: unknown" index signatures json-schema-to-typescript adds
// for nested objects — our schemas use additionalProperties: false.
function postprocess(src) {
  const enumMap = [
    [/(control_paradigm\??\s*:\s*)'prevention' \| 'detection' \| 'correction' \| 'recovery';/g,
      '$1ControlParadigm;'],
    [/(temporal_phase\??\s*:\s*)'pre_generation' \| 'in_generation' \| 'post_generation';/g,
      '$1TemporalPhase;'],
    [/(autonomy_level\??\s*:\s*)'fully_autonomous' \| 'graduated_hitl' \| 'full_hitl';/g,
      '$1AutonomyLevel;'],
    [/(maturity_status\??\s*:\s*)'experimental' \| 'stable' \| 'at_risk' \| 'deprecated' \| 'abandoned';/g,
      '$1MaturityStatus;'],
    [/(confidence\??\s*:\s*)'exact' \| 'partial' \| 'broader' \| 'narrower' \| 'related';/g,
      '$1CrosswalkConfidence;'],
    [/(saica_axis\??\s*:\s*)'failure_mode' \| 'control_paradigm' \| 'temporal_phase' \| 'autonomy_level' \| 'locus_of_control';/g,
      '$1SaicaAxis;'],
  ];

  let out = src;
  for (const [re, repl] of enumMap) {
    out = out.replace(re, repl);
  }

  // Collapse list-of-locus-of-control and list-of-failure-modes.
  out = out.replace(
    /\(\s*'model' \| 'prompt' \| 'context' \| 'environment' \| 'human'\s*\)\[\]/g,
    'LocusOfControl[]',
  );
  out = out.replace(
    /\([\s\S]*?'fabrication'[\s\S]*?'supply_chain_attack'\s*\)(\[\])?/g,
    (m) => (m.endsWith('[]') ? 'FailureModeId[]' : 'FailureModeId'),
  );

  // Drop the noisy index signatures (additionalProperties: false already).
  out = out.replace(/\s*\[k: string\]: unknown;\n/g, '\n');

  // Collapse [T, ...T[]] tuple types (emitted for minItems:1 arrays) into
  // plain T[]. We enforce minItems at schema load time; the TS type doesn't
  // need the extra complexity.
  //
  // Pattern: "X: [\s*<T>,\s*\.\.\.<T>\[\]\s*];" - handle T as string,
  // plain identifiers, or object blocks.
  out = out.replace(
    /\[\s*([A-Za-z_$][\w$]*),\s*\.\.\.\1\[\]\s*\]/g,
    '$1[]',
  );
  // Collapse enum-union tuple form: [(X | Y | Z), ...(X | Y | Z)[]] → (X|Y|Z)[]
  out = collapseEnumUnionTuples(out);
  // Object-literal tuple collapse: [{...}, ...{...}[]] → {...}[]
  // We identify these by matching the repeated object block.
  out = collapseObjectTuples(out);

  return out;
}

// Collapse [(UNION), ...(UNION)[]] → (UNION)[].
// Uses paren matching to grab each arm.
function collapseEnumUnionTuples(src) {
  const out = [];
  let i = 0;
  while (i < src.length) {
    const open = src.indexOf('[\n', i);
    if (open === -1) {
      out.push(src.slice(i));
      break;
    }
    out.push(src.slice(i, open));
    let j = open + 2;
    while (j < src.length && /\s/.test(src[j])) j++;
    if (src[j] !== '(') {
      out.push('[\n');
      i = open + 2;
      continue;
    }
    // Match first paren group
    const firstOpen = j;
    let depth = 0;
    let k = j;
    for (; k < src.length; k++) {
      if (src[k] === '(') depth++;
      else if (src[k] === ')') {
        depth--;
        if (depth === 0) { k++; break; }
      }
    }
    const firstArm = src.slice(firstOpen, k);
    let m = k;
    while (m < src.length && /[,\s]/.test(src[m])) m++;
    if (src.slice(m, m + 3) !== '...') {
      out.push('[\n');
      i = open + 2;
      continue;
    }
    m += 3;
    if (src[m] !== '(') {
      out.push('[\n');
      i = open + 2;
      continue;
    }
    const secondOpen = m;
    depth = 0;
    let n = m;
    for (; n < src.length; n++) {
      if (src[n] === '(') depth++;
      else if (src[n] === ')') {
        depth--;
        if (depth === 0) { n++; break; }
      }
    }
    const secondArm = src.slice(secondOpen, n);
    if (src.slice(n, n + 2) !== '[]') {
      out.push('[\n');
      i = open + 2;
      continue;
    }
    let p = n + 2;
    while (p < src.length && /\s/.test(src[p])) p++;
    if (src[p] !== ']') {
      out.push('[\n');
      i = open + 2;
      continue;
    }
    if (firstArm === secondArm) {
      out.push(firstArm + '[]');
      i = p + 1;
    } else {
      out.push(src.slice(open, p + 1));
      i = p + 1;
    }
  }
  return out.join('');
}

// Walk the source and find patterns of the form
//   categories: [ {BLOCK}, ...{BLOCK}[] ];
// where the two BLOCKs are identical. Collapse to
//   categories: {BLOCK}[];
// This is a lightweight, character-counting brace walker rather than a
// regex, so it correctly handles nested braces inside BLOCK.
function collapseObjectTuples(src) {
  const out = [];
  let i = 0;
  while (i < src.length) {
    const open = src.indexOf('[\n', i);
    if (open === -1) {
      out.push(src.slice(i));
      break;
    }
    out.push(src.slice(i, open));

    // Expect:
    //   [\n<ws>{...first block...},\n<ws>...{...second block...}[]\n<ws>]
    // Find the first "{" after "[\n".
    let j = open + 2;
    while (j < src.length && /\s/.test(src[j])) j++;
    if (src[j] !== '{') {
      out.push('[\n');
      i = open + 2;
      continue;
    }
    // Scan the first block until matching closing brace.
    const firstOpen = j;
    let depth = 0;
    let k = j;
    for (; k < src.length; k++) {
      if (src[k] === '{') depth++;
      else if (src[k] === '}') {
        depth--;
        if (depth === 0) { k++; break; }
      }
    }
    const firstBlock = src.slice(firstOpen, k);
    // Expect ",\n<ws>...{...second block...}[]\n<ws>]"
    let m = k;
    while (m < src.length && /[,\s]/.test(src[m])) m++;
    if (src.slice(m, m + 3) !== '...') {
      out.push('[\n');
      i = open + 2;
      continue;
    }
    m += 3;
    if (src[m] !== '{') {
      out.push('[\n');
      i = open + 2;
      continue;
    }
    const secondOpen = m;
    depth = 0;
    let n = m;
    for (; n < src.length; n++) {
      if (src[n] === '{') depth++;
      else if (src[n] === '}') {
        depth--;
        if (depth === 0) { n++; break; }
      }
    }
    const secondBlock = src.slice(secondOpen, n);
    if (src.slice(n, n + 2) !== '[]') {
      out.push('[\n');
      i = open + 2;
      continue;
    }
    // Find the closing "]" of the tuple.
    let p = n + 2;
    while (p < src.length && /\s/.test(src[p])) p++;
    if (src[p] !== ']') {
      out.push('[\n');
      i = open + 2;
      continue;
    }

    if (firstBlock === secondBlock) {
      out.push(firstBlock + '[]');
      i = p + 1;
    } else {
      // Not a collapsible tuple; emit as-is.
      out.push(src.slice(open, p + 1));
      i = p + 1;
    }
  }
  return out.join('');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
