"""Markdown renderer for AuditReport.

Produces one self-contained Markdown document. It is meant to be read
outside the site, so every link is absolute. Sections, in order:

  # Audit: <repo>
  **Audited:** YYYY-MM-DD

  ## Executive summary
  ## Detected stack          (compact table)
  ## Coverage                 (failure mode × paradigm tier table)
  ## Gaps and recommendations (one subsection per gap)
  ## Not assessable           (only if any)
  ## Recognised, not in the catalog  (only if any)
  ## Limits of this audit

  ---
  Generated by the SAICA audit — https://saica.ai/assess/
"""

from __future__ import annotations

from typing import Iterable

from pipeline.audit.coverage import PARADIGMS
from pipeline.audit.kg import fm_display, load_failure_modes
from pipeline.audit.schemas import (
    AuditLimits,
    AuditReport,
    CoverageGrid,
    DetectedStack,
    GapItem,
    Recommendation,
)

SITE = "https://saica.ai"


def _repo_label(repo_url: str) -> str:
    return repo_url.rstrip("/").rsplit("/", 1)[-1] or repo_url


def _join_or_dash(items: Iterable[str]) -> str:
    items = [i for i in items if i]
    return ", ".join(items) if items else "—"


def _unique(items: Iterable[str]) -> list[str]:
    return list(dict.fromkeys(items))


def tool_link(tool_id: str) -> str:
    """Absolute URL of a tool page on the site."""
    return f"{SITE}/tools/{tool_id}/"


def _render_stack_table(stack: DetectedStack) -> str:
    agents = _join_or_dash(f"{a.name} ({a.id})" for a in stack.agents)
    # A tool seen in two places is one tool: name it once.
    sup = _join_or_dash(_unique(t.name for t in stack.supervision_tools if t.in_kg))
    rows = [
        ("Languages", _join_or_dash(stack.languages)),
        ("Runtime hints", _join_or_dash(stack.runtime_hints)),
        ("Package managers", _join_or_dash(stack.package_managers)),
        ("CI providers", _join_or_dash(stack.ci_providers)),
        ("Coding agents", agents),
        ("Catalog tools found", sup),
    ]
    out = ["| Signal | Value |", "| --- | --- |"]
    for k, v in rows:
        out.append(f"| {k} | {v} |")
    return "\n".join(out)


def _render_coverage_table(coverage: CoverageGrid) -> str:
    fm_ids = load_failure_modes()
    blind = set(coverage.failure_modes_not_assessable)
    by_fm: dict[str, dict[str, int]] = {}
    for cell in coverage.cells:
        by_fm.setdefault(cell.failure_mode, {})[cell.paradigm] = cell.tier

    headers = ["Failure mode"] + [p.title() for p in PARADIGMS]
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join(["---"] * len(headers)) + " |",
    ]
    for fm in fm_ids:
        row = [fm_display(fm)]
        for paradigm in PARADIGMS:
            tier = by_fm.get(fm, {}).get(paradigm, 0)
            if tier > 0:
                row.append(str(tier))
            else:
                row.append("n/a" if fm in blind else "·")
        lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines)


def _render_recommendation(rec: Recommendation) -> str:
    surfaces = ", ".join(rec.integration_surfaces) or "—"
    star_str = f" · {rec.stars}★" if rec.stars else ""
    return (
        f"  - **[{rec.tool_name}]({tool_link(rec.tool_id)})** "
        f"({rec.paradigm} · {rec.temporal_phase}{star_str}) — {rec.why} "
        f"_Surfaces: {surfaces}._"
    )


def _render_gap(gap: GapItem) -> str:
    parts = [
        f"### {fm_display(gap.failure_mode)} — {gap.severity.upper()}",
        gap.rationale,
    ]
    parts.append("")
    if gap.recommendations:
        wanted = f"{gap.paradigm} " if gap.paradigm else ""
        parts.append(f"Catalog {wanted}tools tagged for this mode:")
        parts.extend(_render_recommendation(r) for r in gap.recommendations)
    else:
        parts.append(
            "_The catalog has no tool to suggest for this mode that fits this "
            "repository's languages._"
        )
    return "\n".join(parts)


def _render_not_assessable(coverage: CoverageGrid) -> str:
    if not coverage.failure_modes_not_assessable:
        return ""
    names = ", ".join(fm_display(fm) for fm in coverage.failure_modes_not_assessable)
    return "\n".join(
        [
            "## Not assessable",
            "",
            f"{names}.",
            "",
            "The audit has no detection rule for any catalog tool tagged for "
            "these modes, so it cannot tell whether this repository covers them. "
            "They are shown as `n/a` in the table and are not counted as gaps.",
        ]
    )


def _render_unresolved(stack: DetectedStack) -> str:
    if not stack.unresolved_tools:
        return ""
    lines = [
        "## Recognised, not in the catalog",
        "",
        "The audit recognised these tools, but the catalog does not list them "
        "(it holds tools that supervise AI coding agents; some entries were "
        "removed when their tags were reviewed). They add nothing to the "
        "coverage table above.",
        "",
    ]
    seen: set[str] = set()
    for t in stack.unresolved_tools:
        if t.name in seen:
            continue
        seen.add(t.name)
        paths = ", ".join(t.detection_paths) or "—"
        lines.append(f"- **{t.name}** (source: {t.detection_source}; paths: {paths})")
    return "\n".join(lines)


def _render_limits(limits: AuditLimits) -> str:
    lines = [
        "## Limits of this audit",
        "",
        f"- The audit can detect {len(limits.detectable_tools)} of the "
        f"{limits.catalog_tools} catalog tools: "
        f"{_join_or_dash(limits.detectable_tools)}.",
    ]
    if limits.undetectable_tools:
        lines.append(
            f"- It cannot detect the other {len(limits.undetectable_tools)}: "
            f"{', '.join(limits.undetectable_tools)}. If you use one of them, "
            "the report does not show it."
        )
    lines.extend(f"- {note}" for note in limits.notes)
    if limits.files_listed is not None:
        lines.append(
            f"- This run listed {limits.files_listed} files and read "
            f"{limits.files_read or 0} of them ({limits.bytes_read or 0} bytes)."
        )
    lines.extend(f"- Cut short: {reason}" for reason in limits.truncated)
    return "\n".join(lines)


def to_markdown(report: AuditReport) -> str:
    """Render a complete AuditReport as Markdown."""
    repo = _repo_label(report.repo_url)
    lines: list[str] = []

    lines.append(f"# Audit: [{repo}]({report.repo_url})")
    lines.append("")
    lines.append(f"**Audited:** {report.audited_at.isoformat()}")
    lines.append("")
    lines.append("## Executive summary")
    lines.append("")
    lines.append(report.summary.strip())
    lines.append("")
    lines.append("## Detected stack")
    lines.append("")
    lines.append(_render_stack_table(report.stack))
    lines.append("")
    lines.append("## Coverage")
    lines.append("")
    lines.append(
        "Each cell shows what the catalog says about the tools found, for one "
        "failure mode and one paradigm. `1` = a found tool is tagged for the "
        "mode, `2` = its catalog entry also discusses the mode, `3` = it also "
        "cites a paper or an evaluation, `·` = no found tool, `n/a` = the "
        "audit cannot assess this mode. A tier is not a measurement of how "
        "well a tool works."
    )
    lines.append("")
    lines.append(_render_coverage_table(report.coverage))
    lines.append("")
    lines.append(
        "_Modes covered per paradigm:_ "
        + ", ".join(f"{p}={n}" for p, n in report.coverage.paradigm_balance.items())
    )
    lines.append("")
    lines.append("## Gaps and recommendations")
    lines.append("")
    if report.gaps:
        for gap in report.gaps:
            lines.append(_render_gap(gap))
            lines.append("")
    else:
        lines.append("_No gaps found among the modes this audit can assess._")
        lines.append("")

    for block in (
        _render_not_assessable(report.coverage),
        _render_unresolved(report.stack),
        _render_limits(report.limits) if report.limits else "",
    ):
        if block:
            lines.append(block)
            lines.append("")

    lines.append("---")
    lines.append(f"Generated by the SAICA audit — {SITE}/assess/")

    return "\n".join(lines).rstrip() + "\n"


__all__ = ["SITE", "to_markdown", "tool_link"]
